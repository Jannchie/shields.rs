//! Build script for shields crate.
//!
//! Converts the JSON font width tables into ready-made `CharWidthMeasurer`
//! statics in OUT_DIR, so the library performs no JSON parsing and no lazy
//! initialization at runtime.
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::Path;

const FONT_TABLES: [(&str, &str); 4] = [
    ("VERDANA_11_NORMAL", "assets/fonts/verdana-11px-normal.json"),
    ("HELVETICA_11_BOLD", "assets/fonts/helvetica-11px-bold.json"),
    ("VERDANA_10_NORMAL", "assets/fonts/verdana-10px-normal.json"),
    ("VERDANA_10_BOLD", "assets/fonts/verdana-10px-bold.json"),
];

fn main() -> io::Result<()> {
    println!("cargo:rerun-if-changed=build.rs");
    generate_font_tables()
}

/// Width of `code` in the sorted range table, as `CharWidthMeasurer` looks it up.
fn lookup(ranges: &[(u32, u32, f64)], code: u32) -> Option<f64> {
    let idx = ranges.partition_point(|&(lower, _, _)| lower <= code);
    let &(_, upper, width) = ranges.get(idx.checked_sub(1)?)?;
    (code <= upper).then_some(width)
}

fn generate_font_tables() -> io::Result<()> {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    let mut code = String::from(
        "// Generated by build.rs from assets/fonts/*.json. Do not edit.\n\
         use crate::measurer::CharWidthMeasurer;\n",
    );
    for (name, path) in &FONT_TABLES {
        println!("cargo:rerun-if-changed={path}");
        let json = fs::read_to_string(path)?;
        let ranges: Vec<(u32, u32, f64)> = serde_json::from_str(&json)
            .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e.to_string()))?;
        assert!(
            ranges.windows(2).all(|w| w[0].1 < w[1].0),
            "{path}: font ranges must be sorted and non-overlapping"
        );

        // Sorted, non-overlapping (lower, upper, width) code point ranges.
        writeln!(
            code,
            "static {name}_RANGES: [(u32, u32, f64); {}] = [",
            ranges.len()
        )
        .unwrap();
        for (lower, upper, width) in &ranges {
            writeln!(code, "    ({lower}, {upper}, {width:?}),").unwrap();
        }
        code.push_str("];\n");

        // Direct ASCII lookup; NaN marks a code point missing from the table.
        let ascii: Vec<Option<f64>> = (0..128).map(|c| lookup(&ranges, c)).collect();
        let em_width = ascii[b'm' as usize].unwrap_or(0.0);
        writeln!(
            code,
            "pub static {name}: CharWidthMeasurer = CharWidthMeasurer::from_precomputed(\n    &{name}_RANGES,\n    ["
        )
        .unwrap();
        for width in ascii {
            match width {
                Some(w) => writeln!(code, "        {w:?},").unwrap(),
                None => code.push_str("        f64::NAN,\n"),
            }
        }
        writeln!(code, "    ],\n    {em_width:?},\n);").unwrap();
    }
    fs::write(Path::new(&out_dir).join("font_tables.rs"), code)
}
